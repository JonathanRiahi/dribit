// Generates the color token blocks (0.12) from palette.js and neutrals.js.
// node tools/skins/gen-skins.js           prints the CSS
// node tools/skins/gen-skins.js --write   replaces the generated block at the end of styles.css
// Never edit that block by hand: change palette.js, run --write, then node tools/skins/check-skins.js.
const fs = require('fs'), path = require('path');
const P = require('./palette.js'), { tint } = require('./neutrals.js');
const EXTRA = {
  neon: {
    light: { img: 'linear-gradient(120deg,#08775C,var(--brand) 45%,var(--brand-2))', mark: 'linear-gradient(90deg,#08775C,var(--brand) 45%,var(--brand-2))', sw: 'linear-gradient(135deg,#08775C,var(--brand) 50%,var(--brand-2))' },
    dark: { img: 'linear-gradient(120deg,#3DD68C,var(--brand) 45%,var(--brand-2))', mark: 'linear-gradient(90deg,#3DD68C,var(--brand) 45%,var(--brand-2))', sw: 'linear-gradient(135deg,#3DD68C,var(--brand) 50%,var(--brand-2))' }
  },
  bronze: {
    light: { img: 'linear-gradient(135deg,#7A4419,#A0602A)', mark: 'linear-gradient(90deg,#7A4419,#A0602A)', sw: 'linear-gradient(135deg,#6E3C14 30%,#C98A4B)' },
    dark: { img: 'linear-gradient(135deg,#F3C893,#D99550)', mark: 'linear-gradient(90deg,#F3C893,#D99550)', sw: 'linear-gradient(135deg,#F3C893 20%,#B8783C)' }
  },
  diamond: {
    light: { img: 'linear-gradient(135deg,var(--brand),var(--brand-2))', mark: 'linear-gradient(90deg,#1D3D6B,#5A4FC8)', sw: 'linear-gradient(135deg,#1D3D6B 30%,#7FC8F0 75%,#C3B5FF)' },
    dark: { img: 'linear-gradient(135deg,#B8ECFF,#A99BFF)', mark: 'linear-gradient(90deg,#B8ECFF,#A99BFF)', sw: 'linear-gradient(135deg,#B8ECFF 20%,#8FD8FF 50%,#A99BFF)' }
  },
  gold: {
    light: { img: 'linear-gradient(135deg,var(--brand),var(--brand-2))', mark: 'linear-gradient(90deg,#1F262B,#8C6107)', sw: 'linear-gradient(135deg,#1F262B 40%,#B7820F)' },
    dark: { img: 'linear-gradient(135deg,#F7D774,#E9A92B)', mark: 'linear-gradient(90deg,#F7D774,#E9A92B)', sw: 'linear-gradient(135deg,#F7D774 30%,#B88618)' }
  }
};
function decl(s, mode) {
  const k = s[mode], N = tint(s, mode), E = (EXTRA[s.id] || {})[mode] || {};
  const d = { '--brand': k.brand, '--brand-deep': k.deep, '--brand-soft': k.soft, '--on-brand': k.on, '--brand-2': k.b2, '--q-accent': 'var(--brand)',
    '--brand-img': E.img || 'none', '--mark-img': E.mark || 'none', '--mark-fill': E.mark ? 'transparent' : 'currentColor',
    '--sw-img': E.sw || 'linear-gradient(135deg,var(--brand) 35%,var(--brand-2))' };
  for (const [t, v] of Object.entries(N)) d['--' + t] = v;
  return Object.entries(d).map(([a, b]) => a + ':' + b).join(';');
}
const START = '/* ---------- 0.12: color tokens (generated by tools/skins/gen-skins.js; do not edit by hand) ---------- */';
const END = '/* ---------- end of generated color tokens ---------- */';
function css() {
  let out = START + '\n';
  out += '/* light (and the base for dark): on <html> for the active color, and on any element that previews another color */\n';
  for (const s of P) out += `[data-skin="${s.id}"]{${decl(s, 'light')}}\n`;
  out += '@media (prefers-color-scheme: dark) {\n';
  for (const s of P) out += `  :root:not([data-theme="light"])[data-skin="${s.id}"], :root:not([data-theme="light"]) [data-skin="${s.id}"]{${decl(s, 'dark')}}\n`;
  out += '}\n';
  for (const s of P) out += `:root[data-theme="dark"][data-skin="${s.id}"], :root[data-theme="dark"] [data-skin="${s.id}"]{${decl(s, 'dark')}}\n`;
  return out + END + '\n';
}
module.exports = { css, START, END };
if (require.main === module) {
  const out = css();
  if (process.argv.includes('--write')) {
    const file = path.join(__dirname, '../../styles.css');
    let s = fs.readFileSync(file, 'utf8');
    const a = s.indexOf(START), b = s.indexOf(END);
    s = a >= 0 && b > a ? s.slice(0, a) + out + s.slice(b + END.length + 1) : s.replace(/\s*$/, '\n\n') + out;
    fs.writeFileSync(file, s);
    console.log('styles.css: color tokens written,', out.length, 'bytes');
  } else process.stdout.write(out);
}
